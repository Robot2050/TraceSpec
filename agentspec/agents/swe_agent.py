"""SWE-bench agent: resolves an issue in a local repo checkout via a shell.

ReAct-style loop with a strict one-command-per-turn format, in the spirit of
mini-SWE-agent.  This harness measures speculative decoding, not task success:
only read-only commands are executed for real (see
`tools.swe_tools.is_read_only_command`); edits / test runs / interpreter
one-liners are generated by the model but NOT executed — the loop feeds back a
neutral success observation, keeping the trajectory shape without side effects.

Two parsing/feedback details matter for greedy decoding:

- `parse_action` strips comment-only and blank lines from the bash block.
  Qwen-scale models like to write their reasoning INTO the block as a
  `# comment`; left in place, the "command" is classified non-read and
  simulated, so the episode spins on 13-character observations without ever
  touching the repository (in earlier runs over 40% of all steps were such
  comment-only no-ops);
- the simulated success observation explicitly tells the model to move on
  instead of re-reading files to "verify" an invisible effect, which is what
  previously drove the duplicate-read short-circuit loops.

The agent additionally tracks failure streaks of *executed* read commands and
escalates against the "flailing" pattern (re-running the same failing lookup,
repeated empty greps, ...):

- after `REFLECT_AFTER_FAILURE_STREAK` consecutive failed commands the base
  loop fires one forced reflect-mode call (via `forced_reflect_prompt`), and
  re-fires after every such further streak while failures persist; the streak
  resets on the first success;
- consecutive duplicate-read short-circuits additionally feed the base loop's
  redundant-cycle guard: a loop-focused forced reflect, then a full
  reflect + re-plan intervention (deep analysis of why the loop formed, then a
  fresh plan that must not repeat exhausted commands); the episode terminates
  with `stuck_loop` only if the cycle resumes after the re-plan;
- unlike the search agent there is no hard block: re-running a command after
  new information is legitimate, so escalation is advisory, never a refusal.
"""
from __future__ import annotations

import logging
import re

from ..backends.base import BaseBackend
from ..config import AgentConfig
from ..datasets import AgentTask
from ..tools.swe_tools import RepoSession, is_read_only_command, run_shell, run_shell_result
from .base import DECISION_INSTRUCTION, Action, LoopAgent

_logger = logging.getLogger(__name__)

SYSTEM_TEMPLATE = """You are an autonomous software engineer resolving a real GitHub issue in the repository `{repo}`.
The repository is checked out at the base commit where the issue still exists, and your shell starts at its root.

How to work:
1. Orient: skim the layout and the files most likely related to the issue.
2. Reproduce: find a concrete way to observe the reported behavior.
3. Diagnose: read the implicated code until you understand the root cause.
4. Fix: apply the smallest change that resolves the issue without breaking existing behavior.
5. Verify: re-check the behavior and review your diff before finishing.

Rules:
- In every response, first write 1-3 sentences of reasoning (what you know so far, what you will do next and why), then output exactly ONE bash command inside a single ```bash ... ``` code block. The reasoning goes OUTSIDE the block; inside the block put ONLY the command itself — no comments, no prose.
- Non-interactive commands only; never open editors, pagers or REPLs (use `cat`, `sed -n`, `grep -n`, `git --no-pager ...`, heredocs with quoted delimiters).
- Stay inside the repository. Do not touch files outside it, and do not run git commands that reach the network (push/fetch/pull/clone).
- Prefer targeted inspections (file + line range) over dumping whole files or the whole tree.
- When you are confident the issue is fixed and verified, finish by running the special command `submit` (inside the bash block)."""

_BASH_BLOCK_RE = re.compile(r"```(?:bash|sh|shell)?\s*\n(.*?)```", re.DOTALL)
_COMMENT_LINE_RE = re.compile(r"^\s*#")


class SWEAgent(LoopAgent):
    # Fire a forced reflect call after this many consecutive failed commands.
    REFLECT_AFTER_FAILURE_STREAK = 3
    # Trajectory ledger prepended to reflect prompts.
    LEDGER_MAX_ENTRIES = 8
    LEDGER_CMD_CHARS = 60

    def __init__(self, backend: BaseBackend, cfg: AgentConfig):
        super().__init__(backend, cfg)
        self.session: RepoSession | None = None
        self._reset_loop_state()

    def _reset_loop_state(self) -> None:
        self.failure_streak = 0
        self.repeat_fail_streak = 0
        self.last_failed_command: str | None = None
        # Failure-streak value at which the last forced reflect fired within
        # the current failure run (None = none fired since the last success).
        # Re-arms every REFLECT_AFTER_FAILURE_STREAK additional failures, so a
        # persistent failure run keeps getting periodic intervention instead
        # of exactly one.
        self._last_reflect_streak: int | None = None
        self._last_step_redundant = False
        self._exec_count = 0
        # normalized read command -> tool-call ordinal of its first execution;
        # exact repeats are short-circuited (the repo is static in this harness)
        self.executed_reads: dict[str, int] = {}
        # rendered ledger lines, oldest first, capped at LEDGER_MAX_ENTRIES
        self.command_history: list[str] = []

    def set_task_context(self, task: AgentTask) -> None:
        self.session = RepoSession(
            repo_dir=task.meta["repo_dir"],
            base_commit=task.meta["base_commit"],
        )
        self._reset_loop_state()

    def teardown_task_context(self) -> None:
        if self.session is not None:
            self.session.cleanup()
            self.session = None

    def initial_messages(self, task: AgentTask) -> list[dict]:
        return [
            {"role": "system", "content": SYSTEM_TEMPLATE.format(repo=task.meta["repo"])},
            {
                "role": "user",
                "content": (
                    "Resolve the following issue in the repository.\n\n"
                    f"{task.query}\n\n"
                    "Repository orientation:\n"
                    f"{self._repo_snapshot()}"
                ),
            },
        ]

    def _repo_snapshot(self) -> str:
        """Small real read-only snapshot of the episode worktree (top-level
        layout + recent commits) so the plan is grounded in the actual
        checkout instead of guesses."""
        if self.session is None:
            return "(unavailable)"
        listing = run_shell(self.session, "ls -1", timeout_s=10, max_chars=1200)
        log = run_shell(
            self.session, "git --no-pager log --oneline -3",
            timeout_s=10, max_chars=400,
        )
        return f"{listing}\nRecent commits:\n{log}"

    def plan_prompt(self) -> str:
        return (
            "Before taking any action, analyze the issue and write a concise "
            "plan: which files/functions are likely involved, how you will "
            "reproduce the problem, the minimal fix you expect, and how you "
            "will verify it before `submit`. Do NOT run any command in this "
            "response."
        )

    def reflect_prompt(self) -> str:
        ledger = "\n".join(self.command_history) or "(no commands yet)"
        return (
            f"[trajectory so far]\n{ledger}\n\n"
            "Evaluate your progress against the trajectory above: what have "
            "you tried, which commands failed and why, and what is your "
            "current hypothesis? Do NOT run any command in this response."
            "\n\n" + DECISION_INSTRUCTION
        )

    def final_prompt(self) -> str:
        return (
            "The investigation ends here. Produce the final investigation "
            "summary: the most likely root cause (file and function), the fix "
            "you applied or would apply, and how you verified or would verify "
            "it. Be concrete — this summary is the episode's final output."
        )

    def finalize_prompt(self) -> str:
        return (
            "You have submitted your fix above. Produce the final "
            "investigation summary: the root cause (file and function), the "
            "fix applied, and how you verified it. Be concrete."
        )

    def forced_reflect_prompt(self, step: int) -> str | None:
        """Fire a reflect call once the failure streak reaches the threshold,
        then re-fire after every REFLECT_AFTER_FAILURE_STREAK additional
        consecutive failures; resets on the first success."""
        streak = max(self.failure_streak, self.repeat_fail_streak)
        if (
            streak >= self.REFLECT_AFTER_FAILURE_STREAK
            and (
                self._last_reflect_streak is None
                or streak - self._last_reflect_streak >= self.REFLECT_AFTER_FAILURE_STREAK
            )
        ):
            self._last_reflect_streak = streak
            _logger.info(
                f"[sweagent] failure_streak={self.failure_streak} "
                f"repeat_fail_streak={self.repeat_fail_streak}: forcing reflection"
            )
            return self.reflect_prompt()
        return None

    def step_was_redundant(self, action: Action, observation: str) -> bool:
        """The duplicate-read short-circuit is the only zero-information
        outcome in this harness; genuine failures still explore."""
        return self._last_step_redundant

    def loop_reflect_prompt(self) -> str:
        return (
            f"Your last {self.REDUNDANT_REFLECT_AT} commands were all executed "
            "before and returned nothing new — you are going in circles over "
            "the same files. The repository has not changed. Decide now: "
            "either investigate something you have NOT looked at yet (a "
            "different file, symbol, or hypothesis), or apply the fix and "
            "`submit`. Do NOT run any command in this response."
        )

    def replan_reflect_prompt(self) -> str:
        ledger = "\n".join(self.command_history) or "(no commands yet)"
        return (
            f"[trajectory so far]\n{ledger}\n\n"
            "You have been re-running commands that were already executed, "
            "gaining nothing new. Analyze honestly before continuing: which "
            "assumption about the root cause turned out wrong, what evidence "
            "are you missing, and which files, symbols, callers, tests or "
            "git history have you NOT examined yet? Do NOT run any command "
            "in this response."
        )

    def replan_prompt(self) -> str:
        return (
            "Write a NEW investigation plan for the remaining steps: name the "
            "concrete files or symbols you have not inspected yet, state your "
            "single most promising new hypothesis, and when you will apply the "
            "fix and `submit`. The plan must not repeat any command from the "
            "trajectory above. Do NOT run any command in this response."
        )

    def reset_escalation_state(self) -> None:
        """Fresh slate after a re-plan: failure streaks and their reflect
        cadence restart (already-run commands stay blocked — they would still
        return nothing new)."""
        super().reset_escalation_state()
        self.failure_streak = 0
        self.repeat_fail_streak = 0
        self.last_failed_command = None
        self._last_reflect_streak = None

    def budget_nudge_prompt(self, remaining_steps: int) -> str:
        return (
            f"[system] Step budget: {remaining_steps} command(s) left. "
            "Converge: if you already understand the root cause, apply the fix "
            "and `submit`; otherwise spend the remaining budget only on the "
            "single most informative missing check."
        )

    def loop_start_prompt(self) -> str | None:
        return (
            "Your plan is noted — the analysis phase is over. Now execute the "
            "first concrete step: 1-3 sentences of reasoning, then one real "
            "bash command that inspects the repository (e.g. `ls -1`, "
            "`grep -rn 'symbol' src/`, `sed -n '1,80p' path/to/file.py`)."
        )

    def format_guidance(self) -> str:
        return (
            "Respond with 1-3 sentences of reasoning, then exactly ONE "
            "```bash ... ``` block containing a single real command (e.g. "
            "`grep -rn 'symbol' .` or `sed -n '1,80p' path/to/file.py`). "
            "A block containing only a `# comment` is NOT a command. "
            "When the fix is in place, finish with the special command `submit`."
        )

    @staticmethod
    def _extract_command(block: str) -> str:
        """Drop comment-only and blank lines from the bash block. Models
        frequently write their reasoning into the block as `# ...` lines;
        executed as-is that classifies as a non-read no-op and the episode
        stalls. Heredoc bodies are kept verbatim (their `#` lines are data)."""
        if "<<" in block:
            return block.strip()
        lines = [
            line for line in block.splitlines()
            if line.strip() and not _COMMENT_LINE_RE.match(line)
        ]
        return "\n".join(lines).strip()

    def parse_action(self, text: str) -> Action:
        match = _BASH_BLOCK_RE.search(text)
        if match is None:
            return Action("invalid", "[format error] No ```bash ... ``` block found.")
        command = self._extract_command(match.group(1))
        if not command:
            return Action(
                "invalid",
                "[format error] The bash block contained only comments — a "
                "comment is not a command and does not inspect anything.",
            )
        if command == "submit":
            return Action("finish", f"{text}\n\n--- captured diff ---\n{self._capture_diff()}")
        return Action("bash", command)

    def execute(self, action: Action) -> str:
        assert self.session is not None
        command = " ".join(action.payload.split())  # normalized for repeat detection
        self._exec_count += 1
        self._last_step_redundant = False
        if is_read_only_command(action.payload):
            first_seen = self.executed_reads.get(command)
            if first_seen is not None:
                # Exact repeat: writes are never executed in this harness, so
                # the repo is static and the output would be byte-identical.
                # Short-circuit instead of replaying the same payload into the
                # context; counts as a failure for the escalation machinery and
                # as a redundant step for the cycle guard.
                self._last_step_redundant = True
                _logger.info(
                    f"[sweagent] duplicate read command short-circuited "
                    f"(first run at call #{first_seen}): {command[:120]}"
                )
                text, returncode = (
                    f"[system] This exact command was already run at tool call "
                    f"#{first_seen} and the repository has not changed since, so "
                    f"its output would be identical to what is already in the "
                    f"conversation. Do something that adds NEW information: "
                    f"inspect a different file or line range, grep for a related "
                    f"symbol, or `submit` if the fix is already in place.",
                    None,
                )
            else:
                text, returncode = run_shell_result(
                    self.session,
                    action.payload,
                    timeout_s=self.cfg.command_timeout_s,
                    max_chars=self.cfg.observation_max_chars,
                )
                self.executed_reads[command] = self._exec_count
        else:
            # Non-read operation: generated but not executed.  A neutral
            # success observation keeps the trajectory shape intact; the note
            # steers the model past the otherwise universal "verify the edit
            # by re-reading the file" loop, which only produces duplicate-read
            # short-circuits (the edit's effect is invisible by design).
            _logger.info(f"[sweagent] non-read command simulated: {command[:120]}")
            text, returncode = (
                "[exit code 0]\n[note] The command was accepted; its effects are "
                "not shown in this environment. Assume it succeeded and move on "
                "to a NEW step — do not re-run it and do not re-read files just "
                "to confirm it. Continue investigating, apply the next change, "
                "or `submit` if the fix is complete.",
                0,
            )
        self._remember(command, returncode)
        if returncode == 0:
            self.failure_streak = 0
            self.repeat_fail_streak = 0
            self.last_failed_command = None
            self._last_reflect_streak = None
        else:
            self.failure_streak += 1
            if command == self.last_failed_command:
                self.repeat_fail_streak += 1
            else:
                self.repeat_fail_streak = 1
            self.last_failed_command = command
            _logger.info(
                f"[sweagent] command failed (rc={returncode}), "
                f"failure_streak={self.failure_streak}, "
                f"repeat_fail_streak={self.repeat_fail_streak}"
            )
        return text

    def _remember(self, command: str, returncode: int | None) -> None:
        """Append one rendered entry to the trajectory ledger (see reflect)."""
        rc = "?" if returncode is None else returncode
        if len(command) > self.LEDGER_CMD_CHARS:
            command = command[: self.LEDGER_CMD_CHARS] + "…"
        self.command_history.append(f"#{self._exec_count} `{command}` (rc={rc})")
        del self.command_history[: -self.LEDGER_MAX_ENTRIES]

    def _capture_diff(self) -> str:
        """Residual working-tree diff at submit. Writes are never executed in
        this harness, so this is normally empty; kept as a sanity trace."""
        if self.session is None:
            return ""
        return run_shell(self.session, "git diff HEAD", timeout_s=30, max_chars=8000)
