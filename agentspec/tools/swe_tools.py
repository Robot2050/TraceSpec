"""SWE-bench tools: a per-episode git worktree plus a guarded shell.

Each episode checks out the instance's base commit into a temporary git
worktree so that (a) the shared repo clone is never mutated and (b) episodes
running concurrently on different GPUs never collide. The agent interacts
through one `bash` tool; the special command `submit` ends the episode.

Execution policy (this harness measures speculative decoding, not task
success): only read-only commands are executed for real; every other command
(edits, test runs, interpreters, ...) is generated by the model but NOT
executed — the agent loop feeds back a neutral `[exit code 0]` observation
instead, so the decode workload keeps the shape of a normal trajectory.
"""
from __future__ import annotations

import logging
import re
import shutil
import subprocess
import uuid
from pathlib import Path

_logger = logging.getLogger(__name__)

# Sandbox policy for executed (read-only) commands: the per-episode worktree
# is disposable, and this denylist is a second line of defense that only
# blocks operations escaping the worktree or touching shared/system state:
#   - git operations reaching the network or remotes (push/fetch/pull/clone/remote)
#   - system-level destructive commands (sudo/mkfs/shutdown/...)
#   - deletion or writes aimed at absolute system paths (/etc, /home, ...)
_SYSTEM_DIRS = r"/(?:etc|usr|bin|sbin|lib|lib64|var|home|root|boot|opt|proc|sys|dev)(?:/|\s|$)"

_DENY_PATTERNS = [
    # git network / shared-state operations
    re.compile(r"\bgit\s+push\b"),
    re.compile(r"\bgit\s+(fetch|pull|clone|remote|submodule)\b"),
    # admin / system / destructive power commands
    re.compile(r"\b(sudo|mkfs|shutdown|reboot|halt|poweroff|fdisk|parted)\b"),
    re.compile(r"\bdd\s+.*\bof=/dev/"),
    # recursive deletion from / or of system directories
    re.compile(r"\brm\s+-[a-zA-Z]*[rR][a-zA-Z]*\s+/(?:\s|$)"),
    re.compile(r"\brm\s+-[a-zA-Z]*[rR][a-zA-Z]*\s+" + _SYSTEM_DIRS),
    # writes (redirection / tee / install / cp / mv) to absolute system paths
    re.compile(r"(?:>>?|\|)\s*tee\s+" + _SYSTEM_DIRS),
    re.compile(r"(?:^|\s)[12]?(?:>>|>\||>)\s*" + _SYSTEM_DIRS),
    re.compile(r"\b(?:cp|mv|install|ln)\b[^;&|]*\s" + _SYSTEM_DIRS),
]


# ---------------------------------------------------------------------------
# Read-only command classification
# ---------------------------------------------------------------------------

# Plain read-only tools (no write-capable flags worth special-casing).
_PLAIN_READ_TOOLS = {
    "cat", "ls", "grep", "rg", "egrep", "fgrep", "find", "head", "tail",
    "wc", "file", "stat", "pwd", "tree", "nl", "diff", "echo", "printf",
    "env", "which", "type", "du", "df", "date", "uname", "sort", "uniq",
    "tr", "cut", "comm", "paste", "column", "cd", "true", "false", "test", "[",
}

# git subcommands that never mutate the worktree, index or refs.
_READ_GIT_SUBCOMMANDS = {
    "status", "log", "show", "diff", "blame", "grep", "ls-files", "ls-tree",
    "rev-parse", "describe", "branch", "tag", "shortlog", "reflog", "cat-file",
    "rev-list", "name-rev", "whatchanged",
}

_SED_INPLACE_RE = re.compile(
    r"(?:^|\s)-[a-zA-Z]*i(?:\.[a-zA-Z]*)?(?:\s|$)|--in-place"
)
_REDIRECT_RE = re.compile(r"[12&]?(?:>>?|>\|)")
# Newlines split segments too: a multi-line block ("# note\nls -1") is a
# command sequence, and classifying it by its first token alone mislabels a
# leading comment line as a non-read command.
_SEGMENT_SPLIT_RE = re.compile(r"\|\||&&|[|;\n]")


def _segment_is_read_only(segment: str) -> bool:
    segment = segment.strip()
    if not segment:
        return True
    if _REDIRECT_RE.search(segment):
        return False
    tokens = segment.split()
    head = tokens[0]
    if head == "git":
        return len(tokens) >= 2 and tokens[1] in _READ_GIT_SUBCOMMANDS
    if head == "sed":
        return _SED_INPLACE_RE.search(segment) is None
    if head in {"awk", "gawk"}:
        return "-i" not in tokens and "--inplace" not in tokens
    if head == "find":
        if any(t in ("-delete", "-ok", "-okdir") for t in tokens):
            return False
        # `-exec cmd {} \;` is read-only iff the invoked sub-command is.
        for i, token in enumerate(tokens):
            if token in ("-exec", "-execdir"):
                sub = []
                for t2 in tokens[i + 1:]:
                    if t2 in (";", "\\;", "+"):
                        break
                    sub.append(t2)
                sub = [t for t in sub if t != "{}"]
                if not sub or not _segment_is_read_only(" ".join(sub)):
                    return False
        return True
    if head == "sort":
        return "-o" not in tokens and not any(t.startswith("--output") for t in tokens)
    if head == "xargs":
        return False  # whatever xargs invokes is opaque to this check
    return head in _PLAIN_READ_TOOLS


def is_read_only_command(command: str) -> bool:
    """True iff every pipeline/chain segment of the command is a known
    read-only operation. Anything else (edits, test runs, interpreters,
    opaque one-liners) is classified as non-read and must not be executed."""
    return all(
        _segment_is_read_only(segment)
        for segment in _SEGMENT_SPLIT_RE.split(command)
    )


class WorktreeSetupError(RuntimeError):
    """The per-episode worktree could not be created at the base commit.

    There is deliberately no fallback to the shared checkout: read-only
    commands would then run against whatever HEAD happens to be there and
    silently produce wrong-version trajectories. Failing the episode keeps
    the recorded data honest."""


class RepoSession:
    """A git worktree checked out at the instance's base commit.

    Raises WorktreeSetupError when the worktree cannot be created (missing
    repo, missing commit, git failure); callers must treat that as a failed
    episode rather than run against a stale checkout."""

    def __init__(self, repo_dir: str, base_commit: str, work_root: str | None = None):
        # Absolute paths only: with a relative repo_dir, `git -C repo_dir
        # worktree add <relative work_dir>` resolves work_dir against
        # repo_dir, not against this process's cwd.
        self.repo_dir = Path(repo_dir).resolve()
        self.base_commit = base_commit
        self._owns_worktree = False
        root = Path(work_root).resolve() if work_root else self.repo_dir.parent / ".agentspec_worktrees"
        self.work_dir = root / f"{self.repo_dir.name}-{uuid.uuid4().hex[:8]}"
        self._create()

    def _create(self) -> None:
        self.work_dir.parent.mkdir(parents=True, exist_ok=True)
        try:
            subprocess.run(
                ["git", "-C", str(self.repo_dir), "worktree", "add", "--detach",
                 str(self.work_dir), self.base_commit],
                check=True,
                capture_output=True,
                text=True,
                timeout=300,
            )
            self._owns_worktree = True
        except FileNotFoundError as exc:
            raise WorktreeSetupError(
                f"git executable not found; cannot set up worktree for {self.repo_dir}"
            ) from exc
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
            self._discard_partial()
            if isinstance(exc, subprocess.TimeoutExpired):
                detail = f"git worktree add timed out after {exc.timeout}s"
            else:
                lines = (exc.stderr or "").strip().splitlines()
                detail = lines[-1] if lines else f"exit code {exc.returncode}"
            raise WorktreeSetupError(
                f"cannot create worktree at base_commit {self.base_commit} in "
                f"{self.repo_dir}: {detail}. If the commit is missing, the clone "
                f"is likely shallow — re-clone with full history or fetch it.",
            ) from exc

    def _discard_partial(self) -> None:
        """Best-effort removal of a partially created worktree (a failed or
        timed-out `worktree add` can leave the directory half-populated)."""
        shutil.rmtree(self.work_dir, ignore_errors=True)
        self._prune()

    def _prune(self) -> None:
        """Drop stale worktree administrative entries left behind by rmtree."""
        try:
            subprocess.run(
                ["git", "-C", str(self.repo_dir), "worktree", "prune"],
                capture_output=True,
                timeout=60,
            )
        except Exception:
            pass

    def cleanup(self) -> None:
        if not self._owns_worktree:
            return
        try:
            subprocess.run(
                ["git", "-C", str(self.repo_dir), "worktree", "remove", "--force",
                 str(self.work_dir)],
                check=True,
                capture_output=True,
                text=True,
                timeout=300,
            )
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
            _logger.warning(
                "git worktree remove failed for %s (%s); falling back to rmtree",
                self.work_dir, exc,
            )
            shutil.rmtree(self.work_dir, ignore_errors=True)
            self._prune()
        self._owns_worktree = False

    def __enter__(self) -> "RepoSession":
        return self

    def __exit__(self, *exc) -> None:
        self.cleanup()


def run_shell_result(
    session: RepoSession,
    command: str,
    *,
    timeout_s: int = 60,
    max_chars: int = 4000,
) -> tuple[str, int | None]:
    """Run one shell command inside the episode worktree.

    Returns (text, exit_code); exit_code is None when the command never
    produced one (denied by the sandbox, timed out, or empty) — all of which
    count as failures for the agent's stuck detection."""
    command = command.strip()
    if not command:
        return "[empty command]", None
    for pattern in _DENY_PATTERNS:
        if pattern.search(command):
            return f"[command denied by sandbox policy: {command[:120]}]", None
    try:
        proc = subprocess.run(
            ["bash", "-c", command],
            cwd=session.work_dir,
            capture_output=True,
            text=True,
            timeout=timeout_s,
        )
        output = (proc.stdout or "") + (proc.stderr or "")
        header = f"[exit code {proc.returncode}]"
        returncode: int | None = proc.returncode
    except subprocess.TimeoutExpired:
        return f"[command timed out after {timeout_s}s]", None
    text = f"{header}\n{output.strip()}" if output.strip() else header
    if len(text) > max_chars:
        half = max_chars // 2
        text = text[:half] + f"\n... [{len(text) - max_chars} chars truncated] ...\n" + text[-half:]
    return text, returncode


def run_shell(
    session: RepoSession,
    command: str,
    *,
    timeout_s: int = 60,
    max_chars: int = 4000,
) -> str:
    """Text-only wrapper around `run_shell_result`."""
    text, _ = run_shell_result(
        session, command, timeout_s=timeout_s, max_chars=max_chars
    )
    return text
